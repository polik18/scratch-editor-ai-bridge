export interface CatalogInfo<C extends string> {
  readonly zh: readonly string[]
  readonly category: C
}

const info = <C extends string>(category: C, ...zh: string[]): CatalogInfo<C> => ({ category, zh })

const LETTERS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'.split('')

const entry = (name: string, ...zh: string[]): [string, CatalogInfo<SpriteCategory>] => [name, info('letter', ...zh)]

const letterFamilies: Record<string, CatalogInfo<SpriteCategory>> = Object.fromEntries([
  ...LETTERS.map((letter) => entry(`Block-${letter}`, `字母${letter}`, `積木字母${letter}`)),
  ...LETTERS.map((letter) => entry(`Glow-${letter}`, `發光字母${letter}`, `字母${letter}`)),
  ...LETTERS.map((letter) => entry(`Story-${letter}`, `故事字母${letter}`, `字母${letter}`)),
  ...'0123456789'.split('').map((digit) => entry(`Glow-${digit}`, `數字${digit}`, `發光數字${digit}`)),
])

