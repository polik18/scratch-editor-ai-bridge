/**
 * Musical notes, chords and drum hits follow naming patterns; everything else is listed by name below.
 * @param name - Library sound name.
 * @returns Its catalog entry when a pattern covers it.
 */
const patternSound = (name: string): CatalogInfo<SoundCategory> | undefined => {
  const note = /^([A-G]2?) (.+)$/.exec(name)
  const instrument = note ? NOTE_INSTRUMENTS[note[2]] : undefined
  if (note && instrument) return info('note', `${instrument}${note[1]}`, instrument)
  if (name.endsWith('Ukulele')) return info('note', '烏克麗麗', `烏克麗麗${name.split(' ')[0]}`)
  if (/^Elec Piano [A-G]/.test(name)) return info('note', '電鋼琴和弦', '電鋼琴')
  if (name.endsWith('Tabla')) return info('drum', '塔布拉鼓')
  if (name.endsWith('Conga')) return info('drum', '康加鼓')
  if (/Beatbox2?$|^Beat Box/.test(name)) return info('drum', '人聲節奏', 'Beatbox')
  if (/Cymbal$|^Cymbal/.test(name)) return info('drum', '鈸')
  if (/Snare$|^Snare/.test(name)) return info('drum', '小鼓')
  if (/^Drum Bass|Tom$|^Tom|Kick Drum|High Hat|Cowbell/.test(name)) return info('drum', '鼓')
  return undefined
}

