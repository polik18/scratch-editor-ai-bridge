import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath, URL } from 'node:url'
import Ajv from 'ajv'
import standaloneCode from 'ajv/dist/standalone/index.js'

const generatedRoot = '../src/core/validator/generated/'
const schemaPath = fileURLToPath(new URL('../src/core/ir/schema.json', import.meta.url))
const outputPath = fileURLToPath(new URL(`${generatedRoot}canonical-ir.mjs`, import.meta.url))
const schema = JSON.parse(await readFile(schemaPath, 'utf8'))
const ajv = new Ajv({ allErrors: true, strict: true, code: { source: true, esm: true } })
const validate = ajv.compile(schema)
const replaceRuntimeImport = (source, runtimePath, implementation) => {
  const escapedPath = runtimePath.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  const pattern = new RegExp(`const (func\\d+) = require\\("${escapedPath}"\\)\\.default;`)
  return source.replace(pattern, (_match, name) => implementation(name))
}
const unicodeLengthImplementation = (name) => `const ${name} = (value) => Array.from(value).length;`
const deepEqualImplementation = (name) => `const ${name} = function equal(left, right) {
  if (left === right) return true;
  if (!left || !right || typeof left !== "object" || typeof right !== "object") {
    return Number.isNaN(left) && Number.isNaN(right);
  }
  if (Array.isArray(left) !== Array.isArray(right)) return false;
  const leftKeys = Object.keys(left);
  const rightKeys = Object.keys(right);
  return leftKeys.length === rightKeys.length && leftKeys.every(key =>
    Object.prototype.hasOwnProperty.call(right, key) && equal(left[key], right[key]));
};`
const generated = replaceRuntimeImport(
  replaceRuntimeImport(standaloneCode(ajv, validate), 'ajv/dist/runtime/ucs2length', unicodeLengthImplementation),
  'ajv/dist/runtime/equal',
  deepEqualImplementation,
)
if (generated.includes('require(')) throw new Error('Generated validator contains an unexpected runtime dependency')
const source = `// Generated by scripts/generate-validator.mjs. Do not edit.\n${generated}`

await writeFile(outputPath, source)

const scratchParserSchemaRoot = new URL('../../../node_modules/scratch-parser/lib/', import.meta.url)
const readScratchParserSchema = async (name) =>
  JSON.parse(await readFile(new URL(`${name}.json`, scratchParserSchemaRoot), 'utf8'))
const scratchAjv = new Ajv({ allErrors: true, strict: false, code: { source: true, esm: true } })

for (const name of ['sb3_definitions', 'sb3_schema', 'sprite3_schema']) {
  scratchAjv.addSchema(await readScratchParserSchema(name))
}

const scratchValidators = standaloneCode(scratchAjv, {
  validateSb3Project: 'https://scratch.mit.edu/sb3_schema.json',
  validateSb3Sprite: 'https://scratch.mit.edu/sprite3_schema.json',
})
  .replace(/const (func\d+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/, (_match, name) =>
    unicodeLengthImplementation(name),
  )
  .replace(/const (func\d+) = require\("ajv\/dist\/runtime\/equal"\)\.default;/, (_match, name) =>
    deepEqualImplementation(name),
  )
if (scratchValidators.includes('require(')) {
  throw new Error('Generated Scratch parser validators contain an unexpected runtime dependency')
}

await writeFile(
  fileURLToPath(new URL(`${generatedRoot}scratch-parser.mjs`, import.meta.url)),
  `// Generated from the official scratch-parser 6.0.1 schemas. Do not edit.\n${scratchValidators}`,
)
